//! the CMN/SB/LNTOP/LANE blocks, whose index ranges are 0x000-0x0a7 / 0x100-0x129
//! / 0x200-0x229 / 0x300-0x62d). These are undocumented analog/bias/serializer
//! trim values — correctness = an exact copy of mainline; they cannot be verified
